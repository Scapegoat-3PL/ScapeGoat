import json,re
from pathlib import Path
from playwright.sync_api import sync_playwright
root=Path(__file__).resolve().parent.parent
html=(root/'dist/coverage/index.html').read_text()
html=re.sub(r'<link rel="stylesheet"[^>]+>','',html)
html=re.sub(r'<script type="module"[^>]+></script>','',html)
css=(root/'public/coverage.css').read_text()
css=re.sub(r'@import url\([^;]+;','',css)
data=(root/'.generated/coverageData.js').read_text().replace('export const ','const ').replace('export function ','function ')
code=(root/'.generated/coverage.js').read_text();code=re.sub(r'^import .*?;\n','',code,count=1)
geo=(root/'public/states.json').read_text()
with sync_playwright() as p:
 browser=p.chromium.launch(headless=True,executable_path='/usr/bin/chromium',args=['--no-sandbox'])
 page=browser.new_page(viewport={'width':1440,'height':900},device_scale_factor=1)
 errors=[]
 page.on('pageerror', lambda e: errors.append(str(e)))
 page.set_content(html,wait_until='domcontentloaded')
 page.add_style_tag(content=css)
 page.evaluate('''(g) => {window.history.pushState = ()=>{}; window.history.replaceState=()=>{}; window.fetch=async ()=>new Response(g,{status:200,headers:{'content-type':'application/json'}})}''',geo)
 page.add_script_tag(content=data+'\n'+code)
 page.wait_for_timeout(750)
 print('National',page.locator('h1').first.inner_text(),page.locator('.map-state').count(),page.locator('.key-card').count(),'errors',errors)
 page.screenshot(path=str(root/'national-preview.png'),full_page=False)
 page.locator('.key-card').filter(has_text='West Coast').click()
 print('Region',page.locator('h1').first.inner_text(),page.locator('.key-card').count(),page.locator('.route-core').count())
 page.locator('.key-card').filter(has_text='Southern California').click()
 print('Corridor',page.locator('h1').first.inner_text(),page.locator('.key-card').count(),page.locator('.map-marker--hub').count())
 page.locator('.key-card').filter(has_text='Gardena').click()
 print('Hub',page.locator('h1').first.inner_text(),page.locator('.key-card').count(),page.locator('.service-zone').count())
 page.wait_for_timeout(700)
 page.screenshot(path=str(root/'gardena-preview.png'),full_page=False)
 page.keyboard.press('Escape')
 print('Escape',page.locator('h1').first.inner_text(),'errors',errors)
 mobile=browser.new_page(viewport={'width':390,'height':844},device_scale_factor=1)
 mobile.set_content(html,wait_until='domcontentloaded');mobile.add_style_tag(content=css)
 mobile.evaluate('''(g) => {window.history.pushState=()=>{};window.fetch=async()=>new Response(g,{status:200,headers:{'content-type':'application/json'}})}''',geo)
 mobile.add_script_tag(content=data+'\n'+code)
 mobile.wait_for_timeout(500)
 mobile.screenshot(path=str(root/'mobile-preview.png'),full_page=False)
 print('Mobile grid',mobile.locator('.workspace').evaluate("e=>getComputedStyle(e).gridTemplateRows"))
 browser.close()